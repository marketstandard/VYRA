#!/usr/bin/env python3
"""Generate the paper's data files (paper/data/*.typ) from the results files.

Run from the repository root:

    python paper/tools/gen_data.py

Reads only results/benchmarks.json, results/sizes.json and
results/yield-matrix.json. Writes paper/data/bench.typ, paper/data/sizes.typ
and paper/data/yield.typ. The output is deterministic. The paper never states a
number from these files that is not in the generated data or checked by
paper/tools/check_numbers.py.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "data")


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def fmt1(x):
    return f"{x:.1f}"


def fmt_ms(us):
    return f"{us / 1000:.2f}"


# ------------------------------------------------------------------ benchmarks
def gen_bench():
    b = json.load(open(os.path.join(RES, "benchmarks.json"), encoding="utf8"))
    env = b["environment"]
    lines = [
        "// GENERATED by paper/tools/gen_data.py from results/benchmarks.json. Do not edit.",
        f"// date_utc {env['date_utc']}; cpu {env['cpu']}; {env['rustc']}",
        "// Each row: (group, name, op, n, median_us, p95_us, min_us) as strings, exactly as",
        "// results/benchmarks.json stores them (one decimal; results/benchmarks.md prints the same).",
        f"#let bench-date = {q(env['date_utc'])}",
        f"#let bench-cpu = {q(env['cpu'])}",
        f"#let bench-rustc = {q(env['rustc'])}",
        "#let bench = (",
    ]
    for r in b["results"]:
        lines.append(
            "  ({}, {}, {}, {}, {}, {}, {}),".format(
                q(r["group"]), q(r["name"]), q(r["op"]), r["iterations"],
                q(fmt1(r["median_us"])), q(fmt1(r["p95_us"])), q(fmt1(r["min_us"])),
            )
        )
    lines.append(")")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ sizes
def gen_sizes():
    s = json.load(open(os.path.join(RES, "sizes.json"), encoding="utf8"))
    lines = [
        "// GENERATED by paper/tools/gen_data.py from results/sizes.json. Do not edit.",
        "// Bytes. Category = the NIST category claimed by the component specification.",
    ]
    lines.append("#let size-components = (")
    for c in s["components"]:
        ct = c.get("ciphertext", c.get("signature"))
        ss = c.get("shared_secret", "--")
        lines.append(f"  ({q(c['name'])}, {q(c['kind'])}, {c['level']}, {c['public_key']}, {c['secret_key']}, {ct}, {q(ss)}),")
    lines.append(")")
    keys = list(s.keys())
    lines.append(f"// top-level keys of sizes.json: {', '.join(keys)}")
    return s, lines


def gen_sizes_full():
    s, lines = gen_sizes()
    lines.append("// (suite, id, components, level, pk_raw, pk_wire, sk_raw, sk_wire, ct_raw, ct_wire)")
    lines.append("#let size-kem = (")
    for k in s["kem_suites"]:
        r, w = k["raw"], k["wire"]
        lines.append("  ({}, {}, {}, {}, {}, {}, {}, {}, {}, {}),".format(
            q(k["suite"]), k["suite_id"], q(" + ".join(k["components"])), k["level"],
            r["public_key"], w["public_key"], r["secret_key"], w["secret_key"],
            r["ciphertext"], w["ciphertext"]))
    lines.append(")")
    lines.append("// (suite, family, id, components, level, pk_raw, pk_wire, sk_raw, sk_wire, sig_raw, sig_wire)")
    lines.append("#let size-sig = (")
    for k in s["sig_suites"]:
        r, w = k["raw"], k["wire"]
        lines.append("  ({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}),".format(
            q(k["suite"]), q(k["family"]), k["suite_id"], q(" + ".join(k["components"])), k["level"],
            r["public_key"], w["public_key"], r["secret_key"], w["secret_key"],
            r["signature"], w["signature"]))
    lines.append(")")
    lines.append("// (kem suite, header, kem ciphertext, tag, overhead)")
    lines.append("#let size-seal = (")
    for k in s["seal_suites"]:
        lines.append(f"  ({q(k['suite'])}, {k['header']}, {k['kem_ciphertext']}, {k['tag']}, {k['overhead']}),")
    lines.append(")")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ yield matrix
KEM_PATTERNS = [
    ("Real", "Real"),
    ("Leaky", "Real"), ("Real", "Leaky"), ("Malleable", "Real"), ("Real", "Malleable"),
    ("KeySubstitutable", "Real"), ("Real", "KeySubstitutable"), ("Constant", "Real"),
    ("Real", "Constant"), ("SenderKeyed", "Real"), ("Real", "SenderKeyed"),
    ("Leaky", "Leaky"), ("Malleable", "Malleable"), ("KeySubstitutable", "KeySubstitutable"),
    ("Constant", "Constant"), ("SenderKeyed", "SenderKeyed"), ("Leaky", "Constant"),
]
KEM_GAMES = ["IND-CCA2", "HON-BIND-K-CT", "LEAK-BIND-K-CT", "MAL-BIND-K-CT",
             "HON-BIND-K-PK", "LEAK-BIND-K-PK", "MAL-BIND-K-PK"]
KEM_DESIGNS = ["Naive", "Xor", "CtBound", "XWingStyle", "Vyra"]

SIG_PATTERNS = [
    ("Real", "Real"),
    ("Forgeable", "Real"), ("Real", "Forgeable"), ("Malleable", "Real"), ("Real", "Malleable"),
    ("KeySubstitutable", "Real"), ("Real", "KeySubstitutable"), ("ContextIgnoring", "Real"),
    ("Real", "ContextIgnoring"), ("MessageCollapsing", "Real"), ("Real", "MessageCollapsing"),
    ("Forgeable", "Forgeable"), ("Malleable", "Malleable"),
    ("KeySubstitutable", "KeySubstitutable"), ("ContextIgnoring", "ContextIgnoring"),
    ("MessageCollapsing", "MessageCollapsing"),
]
PQ_PATTERNS = [("Real", "Real"), ("Forgeable", "Real"), ("Real", "Forgeable"),
               ("ContextIgnoring", "Real"), ("Real", "ContextIgnoring")]
SIG_GAMES = ["EUF-CMA", "SUF-CMA", "STRIP-COMPOSITE", "STRIP-STANDALONE", "S-CEO", "MBS",
             "MIX", "CROSS-SUITE", "CROSS-CONTEXT"]
SIG_DESIGNS = ["Vyra", "VyraPureEd", "Concat", "ConcatCtx", "Either"]
PQ_DESIGNS = ["Vyra", "Concat"]
TRIVIAL = {"CoinFlip", "Garbage"}


def pair_of(c):
    if c["primitive"] == "kem":
        return "kem"
    return "pq" if c["component_2"].startswith("SLH-DSA") else "transition"


def gen_yield():
    d = json.load(open(os.path.join(RES, "yield-matrix.json"), encoding="utf8"))
    cells = d["cells"]
    groups = {}
    for c in cells:
        key = (pair_of(c), c["combiner"], c["model_1"], c["model_2"], c["game"])
        groups.setdefault(key, []).append(c)

    def agg(pair, design, m1, m2, game):
        cs = groups.get((pair, design, m1, m2, game))
        if not cs:
            return '"-"'
        broken = [c for c in cs if c["verdict"] == "BROKEN"]
        pre = any(c["expected"] != "UNSPECIFIED" for c in cs if c["adversary"] not in TRIVIAL)
        v = "B" if broken else "N"
        return q(v + ("*" if pre else ""))

    out = [
        "// GENERATED by paper/tools/gen_data.py from results/yield-matrix.json",
        f"// (schema {d['schema']}, master seed {d['master_seed']}). Do not edit.",
        "// Grid cell codes: \"B\" = BROKEN by at least one implemented adversary, \"N\" = NO ATTACK",
        "// FOUND by every implemented adversary, \"-\" = game not run for that pair; a trailing",
        "// \"*\" marks a cell whose non-trivial adversaries carry a pre-stated expectation (claim,",
        "// control or theory); unmarked cells are observations (expected = UNSPECIFIED).",
    ]

    def grid(name, pair, designs, patterns, games):
        out.append(f"#let {name} = (")
        for dsg in designs:
            out.append(f"  {q(dsg)}: (")
            for (m1, m2) in patterns:
                row = ", ".join(agg(pair, dsg, m1, m2, g) for g in games)
                out.append(f"    ({row},),")
            out.append("  ),")
        out.append(")")

    grid("yield-kem", "kem", KEM_DESIGNS, KEM_PATTERNS, KEM_GAMES)
    grid("yield-sig", "transition", SIG_DESIGNS, SIG_PATTERNS, SIG_GAMES)
    grid("yield-pq", "pq", PQ_DESIGNS, PQ_PATTERNS, [g for g in SIG_GAMES if g != "SUF-CMA"])
    out.append("#let kem-patterns = (" + ", ".join(f"({q(a)}, {q(b)})" for a, b in KEM_PATTERNS) + ",)")
    out.append("#let sig-patterns = (" + ", ".join(f"({q(a)}, {q(b)})" for a, b in SIG_PATTERNS) + ",)")
    out.append("#let pq-patterns = (" + ", ".join(f"({q(a)}, {q(b)})" for a, b in PQ_PATTERNS) + ",)")

    # selected exact cells (wins / trials) quoted in the text and in the key-cell table
    sel = [
        ("kem", "Naive", "Malleable", "Real", "IND-CCA2", "MaulReplay-1"),
        ("kem", "Naive", "Real", "Malleable", "IND-CCA2", "MaulReplay-2"),
        ("kem", "Xor", "Real", "Real", "IND-CCA2", "MixAndMatch"),
        ("kem", "XWingStyle", "Malleable", "Real", "IND-CCA2", "MaulReplay-1"),
        ("kem", "XWingStyle", "Real", "Malleable", "IND-CCA2", "MaulReplay-2"),
        ("kem", "CtBound", "KeySubstitutable", "Real", "MAL-BIND-K-PK", "CrossKey-1"),
        ("kem", "Vyra", "Malleable", "Real", "IND-CCA2", "MaulReplay-1"),
        ("kem", "Vyra", "Leaky", "Leaky", "IND-CCA2", "Recompute"),
        ("transition", "VyraPureEd", "Forgeable", "Real", "STRIP-STANDALONE", "Recombine-Default"),
        ("transition", "Vyra", "Forgeable", "Real", "STRIP-STANDALONE", "Recombine-Default"),
        ("transition", "VyraPureEd", "Real", "Real", "STRIP-COMPOSITE", "StripHalf-2"),
        ("transition", "Vyra", "Malleable", "Real", "SUF-CMA", "Maul"),
        ("transition", "Vyra", "ContextIgnoring", "Real", "STRIP-COMPOSITE", "StripHalf-1"),
        ("transition", "Either", "Forgeable", "Real", "EUF-CMA", "Forge"),
        ("pq", "Vyra", "Forgeable", "Real", "EUF-CMA", "Forge"),
        ("pq", "Concat", "Real", "Real", "MIX", "MixHalves"),
    ]
    out.append("// (pair, design, model 1, model 2, game, adversary, wins, trials, verdict, expected basis)")
    out.append("#let yield-key-cells = (")
    for (pair, dsg, m1, m2, g, adv) in sel:
        cs = [c for c in groups[(pair, dsg, m1, m2, g)] if c["adversary"] == adv]
        if len(cs) != 1:
            sys.exit(f"selected cell not unique: {pair} {dsg} {m1} {m2} {g} {adv}")
        c = cs[0]
        out.append("  ({}, {}, {}, {}, {}, {}, {}, {}, {}, {}),".format(
            q(pair), q(dsg), q(m1), q(m2), q(g), q(adv), c["wins"], c["trials"], q(c["verdict"]),
            q(c["expected_basis"])))
    out.append(")")
    return "\n".join(out) + "\n"


def main():
    os.makedirs(OUT, exist_ok=True)
    files = {
        "bench.typ": gen_bench(),
        "sizes.typ": gen_sizes_full(),
        "yield.typ": gen_yield(),
    }
    for name, text in files.items():
        with open(os.path.join(OUT, name), "w", encoding="utf8", newline="\n") as f:
            f.write(text)
        print("wrote paper/data/" + name)


if __name__ == "__main__":
    main()
