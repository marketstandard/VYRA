//! P6 (feature `sig`): the composite-signature message representative
//! `M' = "VYRA-SIG-v1" || suite || digest(32) || u8(len(ctx)) || ctx || message`
//! (docs/SPEC.md §7.3) has a left inverse, hence is injective.
//!
//! The harness calls the real `vyra_sig::message_representative_with_digest`.
//!
//! NOT covered: the public-key digest computation (SHA3-256, assumed collision
//! resistant); context lengths > SIG_MAX_CONTEXT (the function itself rejects
//! contexts longer than 255) and message lengths > SIG_MAX_MESSAGE; the
//! component signature schemes.

// Harness code: every index is checked by the model checker itself.
#![allow(clippy::indexing_slicing)]

use crate::bounds::{SIG_MAX_CONTEXT, SIG_MAX_MESSAGE};
use crate::reference::{SIG_FIXED_LEN, parse_sig_representative};

/// P6 for one shape: for every suite byte, every 32-byte digest, and every
/// context and message of exactly the given lengths (all byte values): the
/// function succeeds, its output has the fixed 44-byte prefix
/// `"VYRA-SIG-v1" || suite || digest` at fixed offsets, and the reference
/// parser recovers exactly (suite, digest, context, message).
fn check_representative(ctx: &[u8], msg: &[u8]) {
    let suite: u8 = kani::any();
    let digest: [u8; 32] = kani::any();

    let Ok(repr) = vyra_sig::message_representative_with_digest(suite, &digest, ctx, msg) else {
        kani::assert(false, "representative rejected a short context");
        return;
    };
    assert!(repr.len() == SIG_FIXED_LEN + 1 + ctx.len() + msg.len());
    assert!(repr[..11] == *b"VYRA-SIG-v1");
    assert!(repr[11] == suite);
    assert!(repr[12..44] == digest);

    let Some((s, d, c, m)) = parse_sig_representative(&repr) else {
        kani::assert(false, "reference parser rejected the representative");
        return;
    };
    assert!(s == suite);
    assert!(d == digest);
    assert!(c == ctx);
    assert!(m == msg);
}

/// One P6 harness per (context length, message length); their union covers
/// context lengths `0..=SIG_MAX_CONTEXT` and message lengths
/// `0..=SIG_MAX_MESSAGE`. Consequence: the representative is injective on
/// that domain (equal outputs parse to equal inputs).
macro_rules! sig_shape {
    ($name:ident, $c:literal, $m:literal) => {
        #[kani::proof]
        #[kani::unwind(34)]
        fn $name() {
            let cb: [u8; SIG_MAX_CONTEXT + 1] = kani::any();
            let mb: [u8; SIG_MAX_MESSAGE + 1] = kani::any();
            check_representative(&cb[..$c], &mb[..$m]);
        }
    };
}

