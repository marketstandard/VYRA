//! Bounded model checking harnesses for the VYRA-original encodings in
//! `vyra-core`, checked with the Kani Rust Verifier.
//!
//! Every harness is compiled only under `cfg(kani)`; on a normal build this
//! crate contains nothing but the [`bounds`] constants, which state the exact
//! input bounds each harness explores. A harness result is a statement of the
//! form "bounded model checking of `<property>` up to `<bound>`": it covers every
//! input within the bound and nothing beyond it.
//!
//! Run with `tools/kani/run.sh` (Linux/Docker) or `tools/kani/run.ps1`
//! (Windows host with Docker Desktop); results are recorded in
//! `tools/kani/RESULTS.md`.
//!
//! | Harness | Property |
//! |---------|----------|
//! | `wire_decode_exact` | P1: `wire::decode` is total and returns exactly the header fields and the payload subslice |
//! | `wire_reader_ops` | P1: every `Reader` operation is total, in bounds, and `finish` succeeds iff all bytes were consumed |
//! | `wire_round_trip_p*` | P2: `decode(encode(t, s, p), u) == Ok((s, p))` iff `t == u` (one harness per payload length) |
//! | `wire_header_rejection` | P2: any header byte that differs from the canonical header is rejected |
//! | `transcript_prefix_inverse` | P3.1: the 8-byte length prefix decodes back to the length, for every `usize` |
//! | `transcript_single_frame` | P3.2: one frame splits back into exactly `(x, rest)` |
//! | `transcript_framing_shape_*` | P3.3: a reference parser recovers (label, fields) from the framed encoding, hence the encoding is injective (one harness per shape of lengths) |
//! | `secret_ct_eq_correct` | P4: `SecretBytes::ct_eq` equals byte-string equality |
//! | `rng_adapter_latches_failure` | P5: `RandCoreRng` is total, zero-fills after any source failure, and `finish` reports it |
//! | `sig_message_representative_c*_m*` | P6 (feature `sig`): a reference parser recovers (suite, digest, context, message) from the signature message representative (one harness per context/message length) |
//!
//! Families marked `*` enumerate every shape (concrete lengths, fully
//! symbolic contents) up to the bound; generated by `tools/kani/gen-shapes.py`.

#![forbid(unsafe_code)]
#![deny(missing_docs)]

/// Input bounds used by the harnesses. Each proof covers exactly the inputs
/// within these bounds.
pub mod bounds {
    /// P1 `wire_decode_exact`: input lengths `0..=DECODE_MAX_LEN`, all byte
    /// values, all seven object types.
    pub const DECODE_MAX_LEN: usize = 24;

    /// P1 `wire_reader_ops`: input lengths `0..=READER_MAX_LEN`.
    pub const READER_MAX_LEN: usize = 64;
    /// P1 `wire_reader_ops`: number of operations (`take` with any `usize`,
    /// `remaining`, `rest`) applied before `finish`.
    pub const READER_MAX_OPS: usize = 5;

    /// P2 `wire_round_trip`: payload lengths `0..=ROUND_TRIP_MAX_PAYLOAD`.
    pub const ROUND_TRIP_MAX_PAYLOAD: usize = 16;
    /// P2 `wire_header_rejection`: payload lengths `0..=HEADER_REJECT_MAX_PAYLOAD`
    /// after an arbitrary 7-byte header.
    pub const HEADER_REJECT_MAX_PAYLOAD: usize = 4;

    /// P3 step 2 (`transcript_single_frame`): framed input lengths
    /// `0..=FRAME_LEMMA_MAX_LEN`.
    pub const FRAME_LEMMA_MAX_LEN: usize = 16;
    /// P3 step 2: lengths `0..=FRAME_LEMMA_MAX_REST` of the bytes after the frame.
    pub const FRAME_LEMMA_MAX_REST: usize = 16;

    /// P3 step 3: label lengths `0..=FRAMING_MAX_LABEL`.
    pub const FRAMING_MAX_LABEL: usize = 3;
    /// P3 step 3: number of fields `0..=FRAMING_MAX_FIELDS`.
    pub const FRAMING_MAX_FIELDS: usize = 3;
    /// P3 step 3: field lengths `0..=FRAMING_MAX_FIELD_LEN`.
    pub const FRAMING_MAX_FIELD_LEN: usize = 3;

    /// P4: secret lengths `0..=CT_EQ_MAX_LEN` (independently for both sides).
    pub const CT_EQ_MAX_LEN: usize = 8;

    /// P5: number of adapter calls (`next_u32`, `next_u64`, `fill_bytes`).
    pub const RNG_MAX_CALLS: usize = 4;
    /// P5: `fill_bytes` buffer lengths `0..=RNG_MAX_FILL`.
    pub const RNG_MAX_FILL: usize = 8;

    /// P6: context lengths `0..=SIG_MAX_CONTEXT`.
    pub const SIG_MAX_CONTEXT: usize = 6;
    /// P6: message lengths `0..=SIG_MAX_MESSAGE`.
    pub const SIG_MAX_MESSAGE: usize = 6;
}

/// Reference decoders used as left inverses in the injectivity proofs.
///
/// If `parse(encode(x)) == x` for every `x` in a domain, then `encode` is
/// injective on that domain: `encode(x) == encode(y)` gives
/// `x = parse(encode(x)) = parse(encode(y)) = y`. These decoders are written
/// independently of the encoders they invert and are not used by the library.
pub mod reference {
    use vyra_core::transcript::FRAME_PREFIX_LEN;

    /// The length a frame prefix announces: `u64` big-endian, converted to
    /// `usize` (`None` if it does not fit).
    pub fn prefix_len(prefix: [u8; FRAME_PREFIX_LEN]) -> Option<usize> {
        usize::try_from(u64::from_be_bytes(prefix)).ok()
    }

    /// Split one frame `u64_be(len) || x` off the front of `bytes`, returning
    /// `(x, rest)`, or `None` if `bytes` is too short.
    pub fn take_frame(bytes: &[u8]) -> Option<(&[u8], &[u8])> {
        let (prefix, rest) = bytes.split_at_checked(FRAME_PREFIX_LEN)?;
        let len = prefix_len(prefix.try_into().ok()?)?;
        rest.split_at_checked(len)
    }

    /// Parse `frame(label) || frame(f1) || ... || frame(fn)` back into the
    /// label and the field list. `None` if the input is not such a string.
    pub fn parse_framed(bytes: &[u8]) -> Option<(&[u8], Vec<&[u8]>)> {
        let (label, mut rest) = take_frame(bytes)?;
        let mut fields = Vec::new();
        while !rest.is_empty() {
            let (field, tail) = take_frame(rest)?;
            fields.push(field);
            rest = tail;
        }
        Some((label, fields))
    }

    /// Length of the fixed prefix of the composite-signature message
    /// representative: `"VYRA-SIG-v1"` (11) || suite id (1) || digest (32).
    pub const SIG_FIXED_LEN: usize = 11 + 1 + 32;

    /// `(suite id, public-key digest, context, message)`.
    pub type SigParts<'a> = (u8, [u8; 32], &'a [u8], &'a [u8]);

    /// Parse a composite-signature message representative
    /// `"VYRA-SIG-v1" || suite || digest(32) || len(ctx) as u8 || ctx || message`
    /// (docs/SPEC.md §7.3) into `(suite, digest, ctx, message)`.
    pub fn parse_sig_representative(bytes: &[u8]) -> Option<SigParts<'_>> {
        let (label, rest) = bytes.split_at_checked(11)?;
        if label != b"VYRA-SIG-v1" {
            return None;
        }
        let (&suite, rest) = rest.split_first()?;
        let (digest, rest) = rest.split_at_checked(32)?;
        let (&ctx_len, rest) = rest.split_first()?;
        let (ctx, message) = rest.split_at_checked(usize::from(ctx_len))?;
        Some((suite, digest.try_into().ok()?, ctx, message))
    }
}

