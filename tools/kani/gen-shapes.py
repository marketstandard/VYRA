#!/usr/bin/env python3
"""Generate the shape-enumerated Kani harness lists in crates/vyra-proofs/src.

Why shapes: CBMC (Kani 0.68 / CBMC 6.11) exhausts 30 GB of memory when slice
LENGTHS are symbolic and the encoder's heap output is parsed back, while each
fixed shape (concrete lengths, fully symbolic CONTENTS) takes a few seconds.
The union of all shapes up to a bound is exactly the bounded domain, so a
family of shape harnesses proves the same statement as one symbolic-length
harness would.

    python tools/kani/gen-shapes.py          # rewrite the generated blocks
    python tools/kani/gen-shapes.py --check  # exit 1 if they are stale

Bounds (must match crates/vyra-proofs/src/lib.rs `bounds`):
"""
import itertools
import pathlib
import sys

FRAMING_MAX_LABEL = 3
FRAMING_MAX_FIELDS = 3
FRAMING_MAX_FIELD_LEN = 3
ROUND_TRIP_MAX_PAYLOAD = 16
SIG_MAX_CONTEXT = 6
SIG_MAX_MESSAGE = 6

ROOT = pathlib.Path(__file__).resolve().parents[2] / "crates" / "vyra-proofs" / "src"
BEGIN = "// BEGIN GENERATED by tools/kani/gen-shapes.py; do not edit by hand.\n"
END = "// END GENERATED\n"


def framing():
    lines = []
    for label in range(FRAMING_MAX_LABEL + 1):
        for n in range(FRAMING_MAX_FIELDS + 1):
            for lens in itertools.product(range(FRAMING_MAX_FIELD_LEN + 1), repeat=n):
                name = f"transcript_framing_shape_l{label}_f" + "_".join(map(str, lens))
                name = name.rstrip("_")
                lines.append(f"framing_shape!({name}, {label}, [{', '.join(map(str, lens))}]);\n")
    return lines


def wire():
    return [f"round_trip_shape!(wire_round_trip_p{p}, {p});\n" for p in range(ROUND_TRIP_MAX_PAYLOAD + 1)]


def sig():
    return [
        f"sig_shape!(sig_message_representative_c{c}_m{m}, {c}, {m});\n"
        for c in range(SIG_MAX_CONTEXT + 1)
        for m in range(SIG_MAX_MESSAGE + 1)
    ]


def splice(path, body):
    text = path.read_text(encoding="utf-8")
    start = text.index(BEGIN) + len(BEGIN)
    stop = text.index(END)
    return text[:start] + "".join(body) + text[stop:]


def main():
    check = "--check" in sys.argv
    stale = False
    for name, body in (("transcript.rs", framing()), ("wire.rs", wire()), ("sig.rs", sig())):
        path = ROOT / name
        new = splice(path, body)
        if new != path.read_text(encoding="utf-8"):
            stale = True
            if not check:
                path.write_bytes(new.encode("utf-8"))
                print(f"updated {path} ({len(body)} harnesses)")
        else:
            print(f"up to date {path} ({len(body)} harnesses)")
    if check and stale:
        print("generated harness lists are stale; run tools/kani/gen-shapes.py", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
